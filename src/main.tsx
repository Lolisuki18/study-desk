import { StrictMode } from 'react'
import { createRoot } from 'react-dom/client'
import { HashRouter } from 'react-router-dom'
import App from './App'
import { ProgressProvider } from './features/learning/ProgressContext'
import { loadSettings } from './services/storage/settings'
import { applyAccent, applyTheme, watchSystemTheme } from './services/theme'
import { initReadingFont } from './utils/fonts'
import './index.css'

// Theme and reading typography first
applyTheme(loadSettings().theme)
applyAccent(loadSettings().accent)
initReadingFont()
watchSystemTheme()

// Offline support: only in the production build (dist/sw.js is generated by `vite build`).
if (import.meta.env.PROD && 'serviceWorker' in navigator) {
  window.addEventListener('load', () => {
    navigator.serviceWorker.register('./sw.js').catch(console.error)
  })
}

createRoot(document.getElementById('root')!).render(
  <StrictMode>
    <HashRouter>
      <ProgressProvider>
        <App />
      </ProgressProvider>
    </HashRouter>
  </StrictMode>,
)
